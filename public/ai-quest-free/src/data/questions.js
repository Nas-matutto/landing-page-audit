/**
 * Limits derived from the battle layout at 320x180 with an 8px font:
 * the question panel wraps at 296px (~37 chars/line, 3 lines) and each option
 * row has ~288px of usable width after its number prefix.
 */
export const LIMITS = { question: 92, option: 34, explain: 78 };

const DIFFICULTIES = ['easy', 'medium', 'hard'];

/**
 * Runs at boot. Overlong strings are the likeliest way to break this UI, and
 * the failure is silent on screen, so it is worth catching the moment a
 * question is added.
 */
export function validateQuestions() {
  const problems = [];
  const seen = new Set();

  for (const q of QUESTIONS) {
    if (seen.has(q.id)) problems.push(`duplicate id "${q.id}"`);
    seen.add(q.id);

    if (!DIFFICULTIES.includes(q.difficulty)) {
      problems.push(`${q.id}: unknown difficulty "${q.difficulty}"`);
    }
    if (q.options.length !== 4) {
      problems.push(`${q.id}: has ${q.options.length} options, expected 4`);
    }
    if (q.answer < 0 || q.answer >= q.options.length) {
      problems.push(`${q.id}: answer index ${q.answer} is out of range`);
    }
    if (new Set(q.options).size !== q.options.length) {
      problems.push(`${q.id}: has duplicate options`);
    }
    if (q.question.length > LIMITS.question) {
      problems.push(`${q.id}: question is ${q.question.length} chars (max ${LIMITS.question})`);
    }
    if (q.explain.length > LIMITS.explain) {
      problems.push(`${q.id}: explain is ${q.explain.length} chars (max ${LIMITS.explain})`);
    }
    q.options.forEach((opt, i) => {
      if (opt.length > LIMITS.option) {
        problems.push(`${q.id}: option ${i} is ${opt.length} chars (max ${LIMITS.option})`);
      }
    });
  }

  if (problems.length) {
    console.warn(`[questions] ${problems.length} issue(s):\n  ${problems.join('\n  ')}`);
  }
  return problems;
}

/** How many questions exist at each difficulty - used by the pool's fallback. */
export function countByDifficulty() {
  return DIFFICULTIES.reduce((acc, d) => {
    acc[d] = QUESTIONS.filter((q) => q.difficulty === d).length;
    return acc;
  }, {});
}
